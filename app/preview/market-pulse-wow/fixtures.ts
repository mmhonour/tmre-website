const SNAPSHOT_GENERATED_AT = "2026-09-14T16:00:00.000Z";

/** Fixture Market Pulse snapshot so the preview can render the real unstacked board. */
export function snapshotFromCombinedRows(
  rows: MarketPulseCombinedTownRow[],
): MarketDigestSnapshot {
  const inventory: MonthsSupplyPayload[] = rows.map((r) => ({
    city: r.city,
    kind: "sale",
    propertyClass: "all",
    activeCount: r.activeCount ?? 0,
    avgMonthlyClosings: null,
    monthsSupply: r.monthsSupply,
    generatedAt: SNAPSHOT_GENERATED_AT,
  }));
  const market = inventory.find((r) => r.city === "All") ?? inventory[0] ?? null;
  const westport = inventory.find((r) => r.city === "Westport") ?? null;
  const towns = inventory.filter((r) => r.city !== "All");
  const closedTrailing = rows
    .filter((r) => r.closedCount != null)
    .map((r) => ({ city: r.city, count: r.closedCount as number }));
  const avgDomByTown = rows
    .filter((r) => r.avgDaysOnMarket != null)
    .map((r) => ({
      city: r.city,
      avgDaysOnMarket: r.avgDaysOnMarket as number,
    }));
  const priceByTown = rows.map((r) => ({
    city: r.city,
    medianPrice: r.medianPrice,
    averagePrice: r.averagePrice,
    priceDelta: r.priceDelta,
    priceDeltaPct: r.priceDeltaPct,
    saleToAskPct: r.saleToAskPct,
    saleToAskDollars: r.saleToAskDollars,
  }));
  const taxByTown = rows.map((r) => ({
    city: r.city,
    medianTax: r.medianTax,
    averageTax: r.averageTax,
    taxDelta: r.taxDelta,
    taxDeltaPct: r.taxDeltaPct,
    taxYearLabel: "FY 2026",
  }));
  const slice = {
    id: "all" as const,
    label: "All",
    scopeLabel: "sales",
    selectionLabel: "All",
    market,
    westport,
    towns,
    closedTrailing,
    avgDomByTown,
    priceByTown,
    taxByTown,
    taxReady: true,
    taxYearLabel: "FY 2026",
    taxYearKind: "current" as const,
    deal: null,
  };
  return {
    generatedAt: SNAPSHOT_GENERATED_AT,
    market,
    westport,
    towns,
    closedTrailing,
    avgDomByTown,
    priceByTown,
    taxByTown,
    taxReady: true,
    taxYearLabel: "FY 2026",
    taxYearKind: "current",
    categories: [slice],
    dealOfTheWeek: null,
    socialProfiles: [],
  };
}
